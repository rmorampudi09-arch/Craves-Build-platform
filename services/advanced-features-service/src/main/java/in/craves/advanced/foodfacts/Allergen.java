package in.craves.advanced.foodfacts;

/**
 * Allergen vocabulary: the FSSAI (Labelling and Display) Regulations 2020 list, plus the further allergens many
 * customers look for. A dish only claims to be free from an allergen when its facts were declared.
 */
public enum Allergen {
    GLUTEN_CEREALS, CRUSTACEANS, MOLLUSCS, EGGS, FISH, PEANUTS, TREE_NUTS, MILK, SOY, SESAME, MUSTARD, CELERY, LUPIN, SULPHITES
}
